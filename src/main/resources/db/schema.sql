-- 새 DB를 준비할 때 SQL Editor에서 수동 실행합니다. 서버 dev 프로필에서는 자동 실행하지 않습니다.
CREATE SCHEMA IF NOT EXISTS alba;
SET SCHEMA 'alba';
CREATE TABLE IF NOT EXISTS region (
    id BIGINT PRIMARY KEY,
    name VARCHAR(30) NOT NULL,
    depth INTEGER NOT NULL CHECK (depth IN (1, 2)),
    parent_id BIGINT REFERENCES region(id)
);
CREATE INDEX IF NOT EXISTS idx_region_parent ON region(parent_id);

CREATE TABLE IF NOT EXISTS job_category (
    code VARCHAR(20) PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    parent_code VARCHAR(20) REFERENCES job_category(code)
);

CREATE TABLE IF NOT EXISTS popular_keyword (
    rank INTEGER PRIMARY KEY CHECK (rank BETWEEN 1 AND 10),
    keyword VARCHAR(100) NOT NULL UNIQUE,
    trend VARCHAR(10) NOT NULL CHECK (trend IN ('UP', 'DOWN', 'STEADY', 'NEW')),
    category_code VARCHAR(20) REFERENCES job_category(code)
);

CREATE TABLE IF NOT EXISTS job_posting (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id BIGINT NOT NULL REFERENCES region(id),
    job_category_code VARCHAR(20) NOT NULL REFERENCES job_category(code),
    company_name VARCHAR(100) NOT NULL,
    title VARCHAR(200) NOT NULL,
    dong VARCHAR(50),
    address_detail VARCHAR(200),
    nearby_subway VARCHAR(100),
    image_url VARCHAR(500),
    apply_method VARCHAR(100),
    in_service_apply BOOLEAN NOT NULL DEFAULT TRUE, -- (데이터) 서비스 내 지원 가능 여부
    pay_type VARCHAR(20) NOT NULL,
    pay_amount INTEGER, -- (데이터) 금액 협의 공고는 NULL
    work_period VARCHAR(30),
    employment_type VARCHAR(20) NOT NULL DEFAULT 'PART_TIME',
    start_time TIME,
    end_time TIME,
    days_negotiable BOOLEAN NOT NULL DEFAULT FALSE,
    time_negotiable BOOLEAN NOT NULL DEFAULT FALSE,
    deadline DATE,
    recruitment_status VARCHAR(20) NOT NULL DEFAULT 'RECRUITING', -- (데이터) 채용 완료 상태 저장
    exposure_type VARCHAR(20) NOT NULL,
    published_at DATE NOT NULL,
    career_requirement VARCHAR(20) NOT NULL DEFAULT 'ANY',
    career_months INTEGER NOT NULL DEFAULT 0,
    preferred_skills VARCHAR(500),
    preferred_certificates VARCHAR(500),
    preferred_language VARCHAR(30),
    preferred_language_level VARCHAR(20),
    computer_skill_preferred BOOLEAN NOT NULL DEFAULT FALSE,
    preferred_computer_skills VARCHAR(500), -- (데이터) 예: 엑셀
    portfolio_preferred BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- (데이터) 이미 만들어진 DB에도 모집 상태 컬럼을 반영한다.
ALTER TABLE job_posting ADD COLUMN IF NOT EXISTS recruitment_status VARCHAR(20) NOT NULL DEFAULT 'RECRUITING';
CREATE INDEX IF NOT EXISTS idx_job_region_published ON job_posting(region_id, published_at DESC, id);
CREATE INDEX IF NOT EXISTS idx_job_category ON job_posting(job_category_code);

CREATE TABLE IF NOT EXISTS posting_workday (
    job_posting_id BIGINT NOT NULL REFERENCES job_posting(id),
    workday VARCHAR(10) NOT NULL,
    PRIMARY KEY (job_posting_id, workday)
);

CREATE TABLE IF NOT EXISTS member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL,
    profile_image_url VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS resume (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member(id),
    title VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,
    desired_region_ids VARCHAR(500),
    desired_category_codes VARCHAR(500),
    workdays_any BOOLEAN NOT NULL DEFAULT FALSE,
    desired_workdays VARCHAR(100),
    work_period_any BOOLEAN NOT NULL DEFAULT FALSE,
    desired_work_periods VARCHAR(300),
    desired_employment_types VARCHAR(200),
    career_category_code VARCHAR(20), -- (데이터) 기존 단일 경력 컬럼 호환용
    career_months INTEGER NOT NULL DEFAULT 0, -- (데이터) 신규 추천에서는 resume_career 사용
    skills VARCHAR(500),
    certificates VARCHAR(500),
    language VARCHAR(30),
    language_level VARCHAR(20),
    computer_skill BOOLEAN NOT NULL DEFAULT FALSE,
    computer_skills VARCHAR(500), -- (데이터) 보유 컴퓨터 활용 항목
    portfolio_category_code VARCHAR(20),
    modified_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_resume_member_modified ON resume(member_id, modified_at DESC, id DESC);

-- (데이터) 이력서에는 여러 업직종 경력이 들어갈 수 있다.
CREATE TABLE IF NOT EXISTS resume_career (
    resume_id BIGINT NOT NULL REFERENCES resume(id) ON DELETE CASCADE,
    career_category_code VARCHAR(20) NOT NULL,
    career_months INTEGER NOT NULL CHECK (career_months >= 0),
    PRIMARY KEY (resume_id, career_category_code)
);

CREATE TABLE IF NOT EXISTS application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member(id),
    job_posting_id BIGINT NOT NULL REFERENCES job_posting(id),
    applied_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_application_member_job UNIQUE(member_id, job_posting_id)
);
